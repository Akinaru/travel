import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

// Documents live on a private volume and are only served through an
// authenticated route (src/app/api/documents/[id]/route.ts), never as static files.

const UPLOAD_DIR = path.resolve(/*turbopackIgnore: true*/ process.env.UPLOAD_DIR ?? "./data/uploads");

export const MAX_UPLOAD_BYTES = 15 * 1024 * 1024;

const EXTENSIONS: Record<string, string> = {
  "application/pdf": "pdf",
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/heic": "heic",
  "image/heif": "heif",
};

export function isAllowedType(mimeType: string) {
  return mimeType in EXTENSIONS;
}

export function extensionFor(mimeType: string) {
  return EXTENSIONS[mimeType] ?? "bin";
}

export async function saveFile(file: File) {
  await mkdir(UPLOAD_DIR, { recursive: true });
  const key = `${randomUUID()}.${extensionFor(file.type)}`;
  await writeFile(path.join(UPLOAD_DIR, key), Buffer.from(await file.arrayBuffer()));
  return key;
}

function filePath(key: string) {
  // Keys are generated by saveFile; reject anything else to stay inside UPLOAD_DIR.
  if (!/^[0-9a-f-]{36}\.[a-z]+$/.test(key)) throw new Error("Clé de fichier invalide");
  return path.join(/*turbopackIgnore: true*/ UPLOAD_DIR, key);
}

export function readStoredFile(key: string) {
  return readFile(filePath(key));
}

export async function deleteStoredFile(key: string) {
  await rm(filePath(key), { force: true });
}
